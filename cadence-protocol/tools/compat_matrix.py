#!/usr/bin/env python3
"""Generate and validate the protocol compatibility matrix.

Usage:
    python3 tools/compat_matrix.py --schemas-dir schemas/ --output docs/COMPATIBILITY_MATRIX.md
    python3 tools/compat_matrix.py --validate --schemas-dir schemas/
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

SCHEMA_STATUS = {
    "envelope": ("canonical", ""),
    "signature": ("canonical", ""),
    "plugin_registry_index": ("canonical", ""),
    "replay_package": ("canonical", ""),
    "registry_entry": ("deprecated_alias", "plugin_registry_index"),
    "replay_bundle": ("deprecated_alias", "replay_package"),
    "signature_envelope": ("deprecated_alias", "signature"),
}

GOVERNED_FAMILIES = [
    "run_manifest",
    "pipeline_result",
    "job_envelope",
    "dataset_manifest",
    "eval_report",
    "plugin_manifest",
    "plugin_registry_index",
    "registry_entry",
    "replay_package",
    "replay_bundle",
    "evidence_bundle",
    "signature",
    "envelope",
    "signature_envelope",
    "sandbox_result",
    "waiver",
    "waiver_file",
    "key_hierarchy",
    "approval_chain",
    "isolation_probe",
    "hsm_anchor",
    "waiver_audit_trail",
    "sandbox_profile",
    "runtime_profile",
]

def collect_schemas(schemas_dir: Path) -> list[dict]:
    """Collect all schema files and extract version info."""
    entries = []
    for schema_path in sorted(schemas_dir.glob("*.schema.json")):
        try:
            data = json.loads(schema_path.read_text(encoding="utf-8"))
        except (json.JSONDecodeError, OSError):
            entries.append({
                "name": schema_path.stem.replace(".schema", ""),
                "version": "PARSE_ERROR",
                "path": (Path("schemas") / schema_path.name).as_posix(),
            })
            continue

        version = data.get("version", data.get("properties", {}).get("schemaVersion", {}).get("const", "unknown"))
        status, alias_of = SCHEMA_STATUS.get(schema_path.stem.replace(".schema", ""), ("canonical", ""))
        entries.append({
            "name": schema_path.stem.replace(".schema", ""),
            "version": str(version),
            "path": (Path("schemas") / schema_path.name).as_posix(),
            "status": status,
            "alias_of": alias_of,
        })
    return entries


def validate(schemas_dir: Path) -> list[str]:
    """Return a list of validation findings.

    Checks JSON parseability, structural requirements, and fixture coverage.
    """
    findings = []
    fixtures_dir = schemas_dir.parent / "fixtures"

    for schema_path in sorted(schemas_dir.glob("*.schema.json")):
        try:
            data = json.loads(schema_path.read_text(encoding="utf-8"))
        except json.JSONDecodeError as e:
            findings.append(f"{schema_path.name}: invalid JSON ({e})")
            continue

        if "$schema" not in data and "type" not in data:
            findings.append(f"{schema_path.name}: missing $schema or type field")

    # Check fixture coverage for governed schema families
    for family in GOVERNED_FAMILIES:
        family_dir = fixtures_dir / family
        if not family_dir.is_dir():
            findings.append(f"fixtures/{family}/: missing directory")
            continue
        valid_dir = family_dir / "valid"
        invalid_dir = family_dir / "invalid"
        if not valid_dir.is_dir() or not list(valid_dir.glob("*.json")):
            findings.append(f"fixtures/{family}/valid/: no valid fixtures")
        if not invalid_dir.is_dir() or not list(invalid_dir.glob("*.json")):
            findings.append(f"fixtures/{family}/invalid/: no invalid fixtures")

    # Check each valid fixture is parseable JSON
    for fixture_json in sorted(fixtures_dir.rglob("*.json")):
        try:
            json.loads(fixture_json.read_text(encoding="utf-8"))
        except json.JSONDecodeError as e:
            findings.append(f"{fixture_json.relative_to(fixtures_dir.parent)}: invalid JSON ({e})")

    # Check compat fixture presence
    compat_dir = fixtures_dir / "compat"
    if not compat_dir.is_dir():
        findings.append("fixtures/compat/: missing directory")
    else:
        compat_files = list(compat_dir.glob("*.json"))
        if not compat_files:
            findings.append("fixtures/compat/: no compatibility fixtures")

    return findings


def generate_matrix(entries: list[dict]) -> str:
    """Generate a markdown compatibility matrix."""
    lines = [
        "# Protocol Compatibility Matrix",
        "",
        "Generated by `tools/compat_matrix.py`.",
        "",
        "| Schema | Version | Status | Alias Of | Path |",
        "|--------|---------|--------|----------|------|",
    ]
    for e in entries:
        lines.append(
            f"| {e['name']} | {e['version']} | {e['status']} | {e['alias_of']} | {e['path']} |"
        )
    lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description="Protocol compatibility matrix tool")
    parser.add_argument("--schemas-dir", required=True, help="Path to schemas directory")
    parser.add_argument("--output", default=None, help="Output file path (default: stdout)")
    parser.add_argument("--validate", action="store_true", help="Validate schemas only")
    args = parser.parse_args()

    schemas_dir = Path(args.schemas_dir)
    if not schemas_dir.is_dir():
        raise SystemExit(f"Not a directory: {schemas_dir}")

    if args.validate:
        findings = validate(schemas_dir)
        if findings:
            for f in findings:
                print(f"FINDING: {f}")
            raise SystemExit(1)
        print("All schemas valid.")
        return

    entries = collect_schemas(schemas_dir)
    matrix = generate_matrix(entries)

    if args.output:
        Path(args.output).write_text(matrix, encoding="utf-8")
        print(f"Written to {args.output}")
    else:
        print(matrix)


if __name__ == "__main__":
    main()
